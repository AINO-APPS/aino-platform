#!/usr/bin/env node
/**
 * Design token pipeline (ticket 04).
 *
 * One machine-readable source — `contracts/design/tokens.json` — generates:
 *   - web      `client/src/styles/tokens.generated.css`
 *   - android  `.../core/designsystem/tokens/WebTokensGenerated.kt`
 *   - ios      `.../Core/DesignSystem/Tokens.swift`
 *
 * Modes:
 *   node scripts/generate-tokens.mjs           regenerate all outputs
 *   node scripts/generate-tokens.mjs --check   verify outputs are current (CI)
 *   node scripts/generate-tokens.mjs --init    derive tokens.json from global.css
 *
 * `--init` exists so the seed can never be hand-retyped: canonical values are
 * read out of the web client's stylesheet, which is what every platform already
 * transcribed. The stylesheet remains the web client's visual source of truth
 * until the generated output is wired in, so the two must agree and the
 * validator enforces it.
 *
 * A sibling platform checkout may be absent — CI checks out only this
 * repository — in which case that platform's output is skipped rather than
 * reported as drift that cannot be seen.
 *
 * Node built-ins only, matching the other scripts in this directory.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { camel, isColourValue, themeVars, toArgb, toSwiftColor } from "./lib/design-tokens.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(root, "..");

const SOURCE = path.join(root, "contracts/design/tokens.json");
const WEB_CSS = path.join(root, "client/src/global.css");

const MODE = process.argv.includes("--check") ? "check" : process.argv.includes("--init") ? "init" : "write";
const BANNER = "Generated by scripts/generate-tokens.mjs from contracts/design/tokens.json. Do not edit.";

/** Token groups this pipeline owns. Order controls emission order. */
const GROUPS = ["color", "space", "typography", "radius", "elevation", "motion", "density"];
const DIMENSION_GROUPS = ["space", "radius", "density", "typography"];

/** Group membership for values a colour predicate would reject (shadows, radii). */
const GROUP_PREFIXES = { radius: "--radius", motion: "--transition", elevation: "--shadow" };

function categorise(vars) {
  const groups = { color: {}, radius: {}, motion: {}, elevation: {} };
  for (const [name, value] of Object.entries(vars)) {
    if (name.startsWith("--sig-")) continue; // chat-only geometry, not core design tokens
    if (isColourValue(value)) groups.color[name] = value;
    else if (name.startsWith("--radius")) groups.radius[name] = value;
    else if (name.startsWith("--transition")) groups.motion[name] = value;
    else if (name.startsWith("--shadow")) groups.elevation[name] = value;
    else if (/^--(control|dropdown|modal).*shadow/.test(name)) groups.elevation[name] = value;
  }
  return groups;
}

/** Derived groups, with light inheriting whatever it does not override — as CSS does. */
function fromStylesheet(dark, light) {
  const merge = (darkGroup, lightGroup) => {
    const out = {};
    for (const [name, value] of Object.entries(darkGroup)) {
      out[name] = { dark: value, light: lightGroup[name] ?? value };
    }
    return out;
  };
  return {
    color: merge(dark.color, light.color),
    radius: merge(dark.radius, light.radius),
    elevation: merge(dark.elevation, light.elevation),
    motion: merge(dark.motion, light.motion),
  };
}

/**
 * Groups the stylesheet cannot supply. `--init` seeds these, but an existing
 * hand-tuned value is preserved so re-running init never destroys a deliberate
 * change.
 */
const CRAFTED_DEFAULTS = {
  space: { "--space-page": "20px", "--space-gutter": "12px", "--space-control": "8px" },
  typography: {
    "--font-body-size": "14px",
    "--font-body-line": "20px",
    "--font-title-size": "18px",
    "--font-title-line": "24px",
    "--font-meta-size": "12px",
  },
  density: {
    "--density-row-comfortable": "44px",
    "--density-row-compact": "32px",
    "--density-touch-target": "44px",
  },
};

function init() {
  const css = fs.readFileSync(WEB_CSS, "utf8");
  const darkVars = themeVars(css, "dark");
  if (!darkVars) throw new Error("global.css has no dark token block");
  const lightVars = themeVars(css, "light") ?? {};

  const previous = fs.existsSync(SOURCE) ? JSON.parse(fs.readFileSync(SOURCE, "utf8")) : null;
  const derived = fromStylesheet(categorise(darkVars), categorise(lightVars));

  const tokens = {};
  for (const group of GROUPS) {
    if (derived[group]) {
      tokens[group] = derived[group];
      continue;
    }
    tokens[group] = {};
    for (const [name, value] of Object.entries(CRAFTED_DEFAULTS[group] ?? {})) {
      tokens[group][name] = previous?.tokens?.[group]?.[name] ?? { dark: value, light: value };
    }
  }

  const source = {
    $comment:
      "Canonical design tokens. Generated file — do not edit by hand. Colour, radius, " +
      "elevation and motion are derived from the web client's stylesheet via " +
      "`npm run tokens:init`; space, typography and density are crafted here and preserved " +
      "across re-runs.",
    version: 1,
    themes: ["dark", "light"],
    tokens,
    outputs: previous?.outputs ?? [
      { platform: "web", path: "aino-platform/client/src/styles/tokens.generated.css" },
      {
        platform: "android",
        path: "aino-android/app/src/main/java/app/aino/mobile/core/designsystem/tokens/WebTokensGenerated.kt",
      },
      { platform: "ios", path: "aino-ios/AinoMobile/Core/DesignSystem/Tokens.swift" },
    ],
    legacyAndroidTokens:
      "aino-android/app/src/main/java/app/aino/mobile/core/designsystem/tokens/WebTokens.kt",
  };

  fs.mkdirSync(path.dirname(SOURCE), { recursive: true });
  fs.writeFileSync(SOURCE, `${JSON.stringify(source, null, 2)}\n`);
  const counts = Object.entries(tokens).map(([g, e]) => `${g}=${Object.keys(e).length}`).join(" ");
  console.log(`tokens: initialised ${SOURCE} (${counts})`);
}

/** Every token is emitted as a custom property, so no group becomes a bare property name. */
function renderCss(source) {
  const lines = [`/* ${BANNER} */`, ""];
  for (const theme of source.themes) {
    lines.push(theme === "dark" ? ':root,\n[data-theme="dark"] {' : `[data-theme="${theme}"] {`);
    for (const group of GROUPS) {
      for (const [name, entry] of Object.entries(source.tokens[group] ?? {})) {
        const value = entry[theme];
        if (value === undefined) continue;
        lines.push(`  ${name}: ${value};`);
      }
    }
    lines.push(theme === "dark" ? "  color-scheme: dark;" : "  color-scheme: light;", "}", "");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

/**
 * Compose reads colour and dimension tokens. Colours keep the ARGB literal so
 * comparisons against an existing `Color(0xFF…)` stay meaningful; dimensions
 * stay strings because stripping the unit for a `Dp` is the caller's decision.
 */
function renderKotlin(source) {
  const colourMap = (name, theme) =>
    `    val ${name}: Map<String, Color> = mapOf(\n${Object.entries(source.tokens.color)
      .map(([key, entry]) => `        "${camel(key)}" to Color(${toArgb(entry[theme])}),`)
      .join("\n")}\n    )`;

  const dimensionMap = (name, group, theme) =>
    `    val ${name}: Map<String, String> = mapOf(\n${Object.entries(source.tokens[group] ?? {})
      .map(([key, entry]) => `        "${camel(key)}" to "${String(entry[theme]).trim()}",`)
      .join("\n")}\n    )`;

  const dimensions = source.themes
    .flatMap(theme =>
      DIMENSION_GROUPS.map(group =>
        dimensionMap(`${theme}${group[0].toUpperCase()}${group.slice(1)}`, group, theme)
      )
    )
    .join("\n\n");

  return `// ${BANNER}
package app.aino.mobile.core.designsystem.tokens

import androidx.compose.ui.graphics.Color

/**
 * Generated from contracts/design/tokens.json.
 *
 * Consume these instead of transcribing values; a hand-typed copy is what the
 * token validator exists to catch. Dimension maps carry CSS units as strings —
 * strip the unit at the call site when converting to Dp or Sp.
 */
object WebTokensGenerated {
${colourMap("dark", "dark")}

${colourMap("light", "light")}

${dimensions}
}
`;
}

function renderSwift(source) {
  const colourMap = (theme) =>
    Object.entries(source.tokens.color)
      .map(([key, entry]) => `        "${camel(key)}": ${toSwiftColor(entry[theme])},`)
      .join("\n");

  const dimensions = source.themes
    .flatMap(theme =>
      DIMENSION_GROUPS.map(group => {
        const entries = Object.entries(source.tokens[group] ?? {})
          .map(([key, entry]) => `        "${camel(key)}": "${String(entry[theme]).trim()}",`)
          .join("\n");
        return `    static let ${theme}${group[0].toUpperCase()}${group.slice(1)}: [String: String] = [\n${entries}\n    ]`;
      })
    )
    .join("\n\n");

  return `// ${BANNER}
import SwiftUI

/// Generated from contracts/design/tokens.json.
enum AinoTokens {
    static let dark: [String: Color] = [
${colourMap("dark")}
    ]

    static let light: [String: Color] = [
${colourMap("light")}
    ]

${dimensions}
}
`;
}

const RENDERERS = { web: renderCss, android: renderKotlin, ios: renderSwift };

/** A platform is present when its repository sibling directory exists. */
function platformRootPresent(outputPath) {
  const [top] = outputPath.split("/");
  return top === "aino-platform" || fs.existsSync(path.join(repoRoot, top));
}

function write() {
  const source = JSON.parse(fs.readFileSync(SOURCE, "utf8"));
  let changed = 0;
  for (const output of source.outputs) {
    if (!platformRootPresent(output.path)) {
      if (MODE !== "check") console.log(`tokens: skipped ${output.platform} (repository not checked out)`);
      continue;
    }
    const absolute = path.resolve(repoRoot, output.path);
    const next = RENDERERS[output.platform](source);
    const previous = fs.existsSync(absolute) ? fs.readFileSync(absolute, "utf8") : null;
    if (previous === next) continue;
    changed += 1;
    if (MODE === "write") {
      fs.mkdirSync(path.dirname(absolute), { recursive: true });
      fs.writeFileSync(absolute, next);
      console.log(`tokens: wrote ${output.path}`);
    }
  }
  return changed;
}

if (MODE === "init") {
  init();
} else {
  const changed = write();
  if (MODE === "check") {
    if (changed > 0) {
      console.error(`tokens: ${changed} generated file(s) are out of date — run npm run tokens:generate`);
      process.exit(1);
    }
    console.log("tokens: generated files are current");
  } else if (changed === 0) {
    console.log("tokens: no changes");
  }
}
