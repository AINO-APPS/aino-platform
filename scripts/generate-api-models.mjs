#!/usr/bin/env node
/**
 * Generated API models (ticket 03).
 *
 * `contracts/openapi.json` is the single source of truth for the task and
 * sprint shapes. This script generates:
 *   - web/Electron  `client/src/types/generated/tasks.ts`
 *   - Android       `.../feature/tasks/generated/TaskModelsGenerated.kt`
 *   - iOS           `.../Features/Tasks/Generated/TaskModelsGenerated.swift`
 *
 * Modes:
 *   node scripts/generate-api-models.mjs           regenerate all outputs
 *   node scripts/generate-api-models.mjs --check   verify outputs are current (CI)
 *
 * A sibling platform checkout may be absent — CI checks out only this
 * repository — in which case that platform's output is skipped rather than
 * reported as drift that cannot be seen.
 *
 * Node built-ins only, matching the other scripts in this directory.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(root, "..");

const SOURCE = path.join(root, "contracts/openapi.json");
const MODE = process.argv.includes("--check") ? "check" : "write";
const BANNER = "Generated by scripts/generate-api-models.mjs from contracts/openapi.json. Do not edit.";

/** Schemas that become client models, in emission order. */
const MODELS = ["Task", "Sprint", "SprintBaseline", "TaskListResponse", "BacklogResponse"];

const OUTPUTS = [
    { platform: "web", path: "aino-platform/client/src/types/generated/tasks.ts" },
    { platform: "android", path: "aino-android/app/src/main/java/app/aino/mobile/feature/tasks/generated/TaskModelsGenerated.kt" },
    { platform: "ios", path: "aino-ios/AinoMobile/Features/Tasks/Generated/TaskModelsGenerated.swift" },
];

function loadSchemas() {
    const api = JSON.parse(fs.readFileSync(SOURCE, "utf8"));
    const schemas = api.components?.schemas ?? {};
    const models = {};
    for (const name of MODELS) {
        const schema = schemas[name];
        if (!schema) throw new Error(`contracts/openapi.json is missing the ${name} schema`);
        models[name] = schema;
    }
    return models;
}

/** Resolve a `$ref` to its schema name. */
function refName(schema) {
    const ref = schema?.$ref;
    if (typeof ref !== "string") return null;
    return ref.split("/").pop();
}

/** Normalise a JSON-schema `type` (string or array) into a list. */
function typesOf(schema) {
    if (!schema) return ["object"];
    if (schema.$ref) return ["ref"];
    const type = schema.type;
    if (Array.isArray(type)) return type;
    if (typeof type === "string") return [type];
    if (schema.properties) return ["object"];
    if (schema.items) return ["array"];
    return ["object"];
}

function isNullable(schema) {
    return typesOf(schema).includes("null");
}

function nonNullTypes(schema) {
    return typesOf(schema).filter((type) => type !== "null");
}

function isRequired(schema, field) {
    return Array.isArray(schema.required) && schema.required.includes(field);
}

/**
 * Hoist inline object schemas into named types so every platform gets a real
 * model instead of an untyped map. Returns the augmented model map.
 */
function hoistInlineObjects(models) {
    const hoisted = { ...models };
    const visit = (schema, ownerName, fieldName) => {
        if (!schema || typeof schema !== "object") return schema;
        if (schema.$ref) return schema;
        if (schema.type === "array" && schema.items) {
            return { ...schema, items: visit(schema.items, ownerName, fieldName) };
        }
        if (schema.properties) {
            const name = `${ownerName}${fieldName[0].toUpperCase()}${fieldName.slice(1)}`;
            const properties = {};
            for (const [field, fieldSchema] of Object.entries(schema.properties)) {
                properties[field] = visit(fieldSchema, name, field);
            }
            hoisted[name] = { ...schema, properties };
            return { $ref: `#/components/schemas/${name}` };
        }
        return schema;
    };

    for (const [name, schema] of Object.entries(models)) {
        const properties = {};
        for (const [field, fieldSchema] of Object.entries(schema.properties ?? {})) {
            properties[field] = visit(fieldSchema, name, field);
        }
        hoisted[name] = { ...schema, properties };
    }
    return hoisted;
}

// ── TypeScript ──────────────────────────────────────────────────────────────

function tsType(schema, indent = "") {
    const ref = refName(schema);
    if (ref) return ref;
    const types = nonNullTypes(schema);
    const parts = types.map((type) => {
        if (type === "integer" || type === "number") return "number";
        if (type === "boolean") return "boolean";
        if (type === "string") return "string";
        if (type === "array") return `${tsType(schema.items, indent)}[]`;
        if (type === "object") {
            if (schema.properties) {
                const inner = Object.entries(schema.properties)
                    .map(([field, fieldSchema]) => {
                        const optional = isRequired(schema, field) ? "" : "?";
                        return `${indent}  ${field}${optional}: ${tsType(fieldSchema, `${indent}  `)};`;
                    })
                    .join("\n");
                return `{\n${inner}\n${indent}}`;
            }
            return "Record<string, unknown>";
        }
        return "unknown";
    });
    const union = parts.length ? parts.join(" | ") : "unknown";
    return isNullable(schema) ? `${union} | null` : union;
}

function renderTypeScript(models) {
    const blocks = Object.entries(models).map(([name, schema]) => {
        const fields = Object.entries(schema.properties ?? {})
            .map(([field, fieldSchema]) => {
                const optional = isRequired(schema, field) ? "" : "?";
                return `  ${field}${optional}: ${tsType(fieldSchema, "  ")};`;
            })
            .join("\n");
        return `export interface ${name} {\n${fields}\n}`;
    });
    return `// ${BANNER}\n\n${blocks.join("\n\n")}\n`;
}

// ── Kotlin ──────────────────────────────────────────────────────────────────

function kotlinType(schema) {
    const ref = refName(schema);
    if (ref) return ref;
    const types = nonNullTypes(schema);
    const base = types.map((type) => {
        if (type === "integer") return "Int";
        if (type === "number") return "Double";
        if (type === "boolean") return "Boolean";
        if (type === "string") return "String";
        if (type === "array") return `List<${kotlinType(schema.items)}>`;
        if (type === "object") return "Map<String, Any?>";
        return "Any?";
    })[0] ?? "Any?";
    return isNullable(schema) ? `${base}?` : base;
}

function renderKotlin(models) {
    const blocks = Object.entries(models).map(([name, schema]) => {
        const fields = Object.entries(schema.properties ?? {})
            .map(([field, fieldSchema]) => {
                const required = isRequired(schema, field);
                const type = kotlinType(fieldSchema);
                if (required) return `    val ${field}: ${type},`;
                const optionalType = type.endsWith("?") ? type : `${type}?`;
                return `    val ${field}: ${optionalType} = null,`;
            })
            .join("\n");
        return `data class ${name}(\n${fields}\n)`;
    });
    return `// ${BANNER}
package app.aino.mobile.feature.tasks.generated

/**
 * Generated from contracts/openapi.json.
 *
 * Consume these instead of hand-maintaining task and sprint models; a field
 * rename in the contract must break the build rather than the running app.
 */
${blocks.join("\n\n")}
`;
}

// ── Swift ───────────────────────────────────────────────────────────────────

function swiftType(schema) {
    const ref = refName(schema);
    if (ref) return ref;
    const types = nonNullTypes(schema);
    const base = types.map((type) => {
        if (type === "integer") return "Int";
        if (type === "number") return "Double";
        if (type === "boolean") return "Bool";
        if (type === "string") return "String";
        if (type === "array") return `[${swiftType(schema.items)}]`;
        if (type === "object") return "[String: AnyCodable]";
        return "AnyCodable";
    })[0] ?? "AnyCodable";
    return isNullable(schema) ? `${base}?` : base;
}

function renderSwift(models) {
    const blocks = Object.entries(models).map(([name, schema]) => {
        const fields = Object.entries(schema.properties ?? {})
            .map(([field, fieldSchema]) => {
                const type = swiftType(fieldSchema);
                const optional = isRequired(schema, field) || type.endsWith("?") ? "" : "?";
                return `    public let ${field}: ${type}${optional}`;
            })
            .join("\n");
        return `public struct ${name}: Codable, Sendable {\n${fields}\n}`;
    });
    return `// ${BANNER}
import Foundation

/// Generated from contracts/openapi.json.
///
/// Consume these instead of hand-maintaining task and sprint models; a field
/// rename in the contract must break the build rather than the running app.
${blocks.join("\n\n")}
`;
}

const RENDERERS = { web: renderTypeScript, android: renderKotlin, ios: renderSwift };

/** A platform is present when its repository sibling directory exists. */
function platformRootPresent(outputPath) {
    const [top] = outputPath.split("/");
    return top === "aino-platform" || fs.existsSync(path.join(repoRoot, top));
}

function write() {
    const models = hoistInlineObjects(loadSchemas());
    let changed = 0;
    for (const output of OUTPUTS) {
        if (!platformRootPresent(output.path)) {
            if (MODE !== "check") console.log(`api-models: skipped ${output.platform} (repository not checked out)`);
            continue;
        }
        const absolute = path.resolve(repoRoot, output.path);
        const next = RENDERERS[output.platform](models);
        const previous = fs.existsSync(absolute) ? fs.readFileSync(absolute, "utf8") : null;
        if (previous === next) continue;
        changed += 1;
        if (MODE === "write") {
            fs.mkdirSync(path.dirname(absolute), { recursive: true });
            fs.writeFileSync(absolute, next);
            console.log(`api-models: wrote ${output.path}`);
        }
    }
    return changed;
}

const changed = write();
if (MODE === "check") {
    if (changed > 0) {
        console.error(`api-models: ${changed} generated file(s) are out of date — run npm run models:generate`);
        process.exit(1);
    }
    console.log("api-models: generated files are current");
} else if (changed === 0) {
    console.log("api-models: no changes");
}
